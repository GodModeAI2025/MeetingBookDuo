import Foundation
import CryptoKit
import PencilKit
import Darwin
import ZIPFoundation
import MeetingBookCore

struct PackageManifest: Codable, Sendable {
    struct File: Codable, Sendable { let path: String; let size: UInt64; let sha256: String }
    let version: Int
    let profile: String
    let exportedAt: Date
    let appVersion: String
    let unsaved: Bool
    let files: [File]
}
struct InspectedPackage: Sendable {
    let rows: [NotebookStore.RecordRow]
    let records: [String:Data]
    let assets: [String:URL]
    let fonts: [FontVersion]
    let notes: Int
    let unsaved: Bool
    let pages: Int
}

/// Serial owner of ZIPFoundation's shared FILE; every emitted archive is independently read back.
actor NotebookPackage {
    let root: URL
    init(root: URL) { self.root=root }
    func create(store: NotebookStore) async throws -> URL {
        let capture=try await store.captureBackup()
        return try await create(capture:capture,assets:store.assets)
    }
    func create(capture: BackupCapture,assets: AssetStore) async throws -> URL {
        let policy:PackageSizePolicy=capture.files.keys.contains(where:{$0.hasPrefix("records/")}) ? .large : .ordinary
        let directory:URL
        do { directory=try PackageIO.directory(in:root) } catch { await assets.releasePin(capture.pin);throw error }
        let url=directory.appendingPathComponent(capture.unsaved ? "UNSAVED-MeetingBook.notebookpkg" : "MeetingBook.notebookpkg")
        do {
            var sources:[String:URL]=[:],metadataSize=0
            for (path,data) in capture.files {
                metadataSize+=data.count;guard metadataSize<=policy.metadataLimit,data.count<=(policy == .large ? 24_000_000 : 16_000_000) else { throw NotebookError.invalidAsset }
                let file=directory.appendingPathComponent(UUID().uuidString);try PackageIO.write(data,to:file);sources[path]=file
            }
            for hash in capture.assetHashes {
                try Task.checkCancellation()
                if let bytes=capture.memoryAssets[hash] {
                    let file=directory.appendingPathComponent(UUID().uuidString);try PackageIO.write(bytes,to:file);sources["assets/"+hash+".blob"]=file
                } else { sources["assets/"+hash+".blob"]=try await assets.verifiedURL(hash:hash) }
            }
            for version in capture.fonts { sources["fonts/"+version.id.uuidString.lowercased()+".ttf"]=try await assets.verifiedURL(hash:version.assetHash) }
            for name in ["Caveat-OFL","GochiHand-OFL","ZIPFoundation-MIT"] {
                guard let file=Bundle.main.url(forResource:name,withExtension:"txt") else { throw NotebookError.notFound }
                sources["licenses/"+name.lowercased()+".txt"]=file
            }
            let personal=directory.appendingPathComponent("personal-license")
            try PackageIO.write(Data("Personal handwriting fonts generated by MeetingBook from user-provided strokes. No third-party font data is included in these generated fonts.\n".utf8),to:personal)
            sources["licenses/personal-fonts.txt"]=personal
            var entries:[PackageManifest.File]=[]
            for path in sources.keys.sorted() {
                let digest=try PackageIO.digest(sources[path]!,maximum:100_000_000)
                entries.append(.init(path:path,size:digest.size,sha256:digest.hash))
            }
            guard entries.count<policy.zipLimits.entries,entries.reduce(UInt64(0),{$0+$1.size})<=1_990_000_000 else { throw NotebookError.invalidAsset }
            let manifest=PackageManifest(version:policy == .large ? 2 : 1,profile:policy == .large ? "zip32-chunked-v2" : "zip32-stored-v1",exportedAt:Date(),appVersion:Bundle.main.infoDictionary?["CFBundleShortVersionString"] as? String ?? "1.0",unsaved:capture.unsaved,files:entries)
            let encoder=JSONEncoder();encoder.outputFormatting = .sortedKeys
            let manifestData=try encoder.encode(manifest);guard manifestData.count<=policy.manifestLimit,manifestData.count<=policy.metadataLimit-metadataSize,UInt64(manifestData.count)<=policy.zipLimits.payload-entries.reduce(UInt64(0),{$0+$1.size}) else { throw NotebookError.invalidAsset }
            let manifestURL=directory.appendingPathComponent("manifest");try PackageIO.write(manifestData,to:manifestURL);sources["manifest.json"]=manifestURL
            try writeArchive(sources,to:url)
            try AssetStore.synchronize(url,false)
            let checked=try inspect(url:url,directory:try PackageIO.directory(in:directory),policy:policy)
            try validateNativeAssets(checked)
            guard checked.records==capture.files else { throw NotebookError.hashMismatch }
            // Only the published package survives; verification and build scratch are disposable.
            for child in try FileManager.default.contentsOfDirectory(at:directory,includingPropertiesForKeys:nil) where child != url { try FileManager.default.removeItem(at:child) }
            try AssetStore.synchronize(directory,true);try Task.checkCancellation();await assets.releasePin(capture.pin);return url
        } catch { await assets.releasePin(capture.pin);try? FileManager.default.removeItem(at:directory);throw error }
    }
    func validateNativeAssets(_ content: InspectedPackage) throws {
        try NotebookStore.validateStoredWireBodies(content.rows,fonts:content.fonts) { hash in
            guard let url=content.assets[hash] else {throw NotebookError.invalidAsset}
            return try Data(contentsOf:url)
        }
        for font in content.fonts {
            try Task.checkCancellation();guard let url=content.assets[font.assetHash] else { throw NotebookError.invalidAsset }
            try PersonalFontService.validateForImport(version:font,data:Data(contentsOf:url))
        }
        var checkedDrawings=Set<String>(),checkedImages=Set<String>(),checkedGlyphs=Set<String>()
        for row in content.rows {
            let data=row.payload
            try Task.checkCancellation()
            if row.kind=="revision" {
                let revision=try JSONDecoder().decode(PageRevision.self,from:data)
                if let hash=revision.content.drawingAssetHash,checkedDrawings.insert(hash).inserted { guard let url=content.assets[hash] else { throw NotebookError.invalidAsset };_ = try PKDrawing(data:Data(contentsOf:url)) }
                for image in revision.content.images {
                    for hash in Set([image.assetHash,image.previewAssetHash].compactMap{$0}) where checkedImages.insert(hash).inserted {
                        guard let url=content.assets[hash] else { throw NotebookError.invalidAsset }
                        var item=ImageElement(frame:image.frame,assetHash:hash,altText:image.altText)
                        if hash==image.previewAssetHash { item.previewAssetHash=hash }
                        var isolated=PageContent();isolated.version=2;isolated.images=[item]
                        try PageClipboard(content:isolated,assets:[hash:try Data(contentsOf:url)],fonts:[]).validate()
                    }
                }
            }
            if row.kind=="library" {
                let library=try JSONDecoder().decode(NotebookStore.Library.self,from:data)
                for hash in library.fonts.flatMap({$0.glyphAssetHashes.values}) where checkedGlyphs.insert(hash).inserted {
                    guard let url=content.assets[hash] else { throw NotebookError.invalidAsset }
                    let bytes=try Data(contentsOf:url);guard bytes.count<=2_000_000 else { throw NotebookError.invalidAsset };_ = try PKDrawing(data:bytes)
                }
            }
        }
    }
    func remove(_ url: URL) throws {
        let directory=url.deletingLastPathComponent()
        guard directory.deletingLastPathComponent()==root,UUID(uuidString:directory.lastPathComponent) != nil,url.pathExtension=="notebookpkg" else { throw NotebookError.invalidModel }
        try FileManager.default.removeItem(at:directory)
    }
    private func writeArchive(_ sources: [String:URL],to url: URL) throws {
        let archive=try Archive(url:url,accessMode:.create)
        try FileManager.default.setAttributes(AssetStore.protection,ofItemAtPath:url.path)
        for path in sources.keys.sorted() {
            try Task.checkCancellation();guard ImportValidation.validPath(path) else { throw NotebookError.invalidModel }
            let file=try PackageIO.openRegular(sources[path]!),size=try file.seekToEnd();try file.seek(toOffset:0)
            do {
                try archive.addEntry(with:path,type:.file,uncompressedSize:Int64(size),permissions:0o600,compressionMethod:.none,bufferSize:65_536) { offset,count in
                    try Task.checkCancellation();try file.seek(toOffset:UInt64(offset))
                    guard let bytes=try file.read(upToCount:count),bytes.count==count else { throw NotebookError.invalidAsset };return bytes
                }
                try file.close()
            } catch { try? file.close();throw error }
        }
    }
    func inspect(url: URL,directory: URL,policy: PackageSizePolicy = .ordinary) throws -> InspectedPackage {
        let inventory=try ImportValidation.inspectZIP(url:url,limits:policy.zipLimits)
        guard inventory.contains(where:{$0.path=="manifest.json"}) else { throw NotebookError.invalidModel }
        let archive=try Archive(url:url,accessMode:.read)
        var extracted:[String:URL]=[:],digests:[String:(size: UInt64,hash: String)]=[:],index=0,metadataSize:UInt64=0
        for entry in archive {
            try Task.checkCancellation();guard index<inventory.count else { throw NotebookError.invalidModel }
            let expected=inventory[index];index+=1
            guard entry.path==expected.path,entry.type == .file,entry.uncompressedSize==expected.size,entry.checksum==expected.crc else { throw NotebookError.invalidModel }
            let cap:UInt64=entry.path=="manifest.json" ? UInt64(policy.manifestLimit) : (entry.path.hasSuffix(".json") ? (policy == .large ? 24_000_000 : 16_000_000) : (entry.path.hasSuffix(".txt") ? 1_000_000 : 100_000_000))
            guard expected.size<=cap else { throw NotebookError.invalidAsset }
            if entry.path.hasSuffix(".json") { metadataSize+=expected.size;guard metadataSize<=UInt64(policy.metadataLimit) else { throw NotebookError.invalidAsset } }
            let destination=directory.appendingPathComponent(UUID().uuidString),file=try PackageIO.create(destination)
            var count:UInt64=0,sha=SHA256()
            do {
                let crc=try archive.extract(entry,bufferSize:65_536) { bytes in
                    try Task.checkCancellation();guard UInt64(bytes.count)<=expected.size-count else { throw NotebookError.invalidAsset }
                    try file.write(contentsOf:bytes);sha.update(data:bytes);count+=UInt64(bytes.count)
                }
                guard count==expected.size,crc==expected.crc else { throw NotebookError.hashMismatch }
                try file.synchronize();try file.close()
            } catch { try? file.close();throw error }
            extracted[entry.path]=destination;digests[entry.path]=(count,sha.finalize().map{String(format:"%02x",$0)}.joined())
        }
        guard index==inventory.count,let manifestURL=extracted["manifest.json"] else { throw NotebookError.invalidModel }
        let manifestData=try Data(contentsOf:manifestURL);try ImportValidation.validateJSON(manifestData,maximum:policy.manifestLimit)
        let manifest=try JSONDecoder().decode(PackageManifest.self,from:manifestData)
        let chunked=manifest.version==2 && manifest.profile=="zip32-chunked-v2"
        guard (manifest.version==1 && manifest.profile=="zip32-stored-v1") || (policy == .large && chunked) else {throw NotebookError.unsupportedVersion}
        if !chunked {
            guard inventory.count<=20_000,metadataSize<=64_000_000,manifestData.count<=8_000_000 else {throw NotebookError.invalidAsset}
        }
        guard inventory.filter({$0.path.hasSuffix(".json") && $0.path != "manifest.json"}).allSatisfy({chunked ? $0.path.hasPrefix("records/") : !$0.path.hasPrefix("records/")}) else {throw NotebookError.invalidModel}
        guard Set(manifest.files.map(\.path)).count==manifest.files.count,Set(manifest.files.map(\.path))==Set(extracted.keys).subtracting(["manifest.json"]) else { throw NotebookError.invalidModel }
        for file in manifest.files {
            guard let digest=digests[file.path],digest.size==file.size,digest.hash==file.sha256 else { throw NotebookError.hashMismatch }
        }
        var records:[String:Data]=[:],assets:[String:URL]=[:]
        for (path,file) in extracted {
            if path.hasSuffix(".json"),path != "manifest.json" {
                let data=try Data(contentsOf:file)
                // The shared chunk decoder validates encoded JSON and every decoded payload.
                if !chunked {try autoreleasepool {try ImportValidation.validateJSON(data)}}
                records[path]=data
            }
            if path.hasPrefix("assets/") { let hash=String(path.dropFirst(7).dropLast(5));guard digests[path]?.hash==hash else { throw NotebookError.hashMismatch };assets[hash]=file }
        }
        let (rows,graph)=try NotebookStore.validatedPackageRows(records)
        guard graph.assetHashes==Set(assets.keys),Set(extracted.keys.filter{$0.hasPrefix("fonts/")})==Set(graph.fonts.map{"fonts/"+$0.id.uuidString.lowercased()+".ttf"}) else { throw NotebookError.invalidModel }
        for font in graph.fonts {
            guard digests["fonts/"+font.id.uuidString.lowercased()+".ttf"]?.hash==font.assetHash else { throw NotebookError.hashMismatch }
        }
        guard extracted["licenses/personal-fonts.txt"] != nil else { throw NotebookError.invalidModel }
        return InspectedPackage(rows:rows,records:records,assets:assets,fonts:graph.fonts,notes:graph.library.notes.count,unsaved:manifest.unsaved,pages:rows.filter{$0.kind=="page"}.count)
    }
}

enum PackageIO {
    static func directory(in parent: URL) throws -> URL {
        try FileManager.default.createDirectory(at:parent,withIntermediateDirectories:true,attributes:AssetStore.protection)
        let url=parent.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at:url,withIntermediateDirectories:false,attributes:AssetStore.protection);return url
    }
    static func openRegular(_ url: URL) throws -> FileHandle {
        let descriptor=Darwin.open(url.path,O_RDONLY|O_NOFOLLOW|O_CLOEXEC)
        guard descriptor>=0 else { throw POSIXError(.EIO) }
        var info=stat()
        guard fstat(descriptor,&info)==0,info.st_mode & S_IFMT == S_IFREG else { Darwin.close(descriptor);throw NotebookError.invalidAsset }
        return FileHandle(fileDescriptor:descriptor,closeOnDealloc:true)
    }
    static func create(_ url: URL) throws -> FileHandle {
        let descriptor=Darwin.open(url.path,O_WRONLY|O_CREAT|O_EXCL|O_NOFOLLOW|O_CLOEXEC,0o600)
        guard descriptor>=0 else { throw POSIXError(.EIO) }
        do { try FileManager.default.setAttributes(AssetStore.protection,ofItemAtPath:url.path) }
        catch { Darwin.close(descriptor);throw error }
        return FileHandle(fileDescriptor:descriptor,closeOnDealloc:true)
    }
    static func write(_ data: Data,to url: URL) throws {
        let file=try create(url)
        do { try file.write(contentsOf:data);try file.synchronize();try file.close() } catch { try? file.close();throw error }
    }
    static func digest(_ url: URL,maximum: UInt64 = 2_016_000_000,copyTo destination: URL? = nil) throws -> (size: UInt64,hash: String) {
        let input=try openRegular(url),output=try destination.map(create);var count:UInt64=0,sha=SHA256()
        do {
            while let data=try input.read(upToCount:65_536),!data.isEmpty {
                try Task.checkCancellation();guard UInt64(data.count)<=maximum-count else { throw NotebookError.invalidAsset }
                try output?.write(contentsOf:data);sha.update(data:data);count+=UInt64(data.count)
            }
            try output?.synchronize();try output?.close();try input.close()
            return (count,sha.finalize().map{String(format:"%02x",$0)}.joined())
        } catch { try? input.close();try? output?.close();throw error }
    }
}

struct SavedPackage: Sendable, Identifiable { let url: URL;let createdAt: Date;var id: URL {url} }
extension NotebookPackage {
    static func saved(in root: URL) throws -> [SavedPackage] {
        guard FileManager.default.fileExists(atPath:root.path) else { return [] }
        var result:[SavedPackage]=[]
        for directory in try FileManager.default.contentsOfDirectory(at:root,includingPropertiesForKeys:nil) where UUID(uuidString:directory.lastPathComponent) != nil {
            let url=directory.appendingPathComponent("MeetingBook.notebookpkg")
            if let attributes=try? FileManager.default.attributesOfItem(atPath:url.path),attributes[.type] as? FileAttributeType == .typeRegular {
                result.append(SavedPackage(url:url,createdAt:attributes[.modificationDate] as? Date ?? .distantPast))
            }
        }
        return result.sorted{$0.createdAt>$1.createdAt}
    }
}
